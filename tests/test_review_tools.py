"""Actual tiny lifecycle + numeric replay, tamper rejection and portable export."""
from __future__ import annotations

import contextlib
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import zipfile

import numpy as np
import torch

from cross_morse.pipeline import Pipeline
from cross_morse.review import EvidenceError, replay_results, assert_matches, safe_file
from cross_morse.reexecution import FrozenRunEvaluator
from scripts.build_review_bundle import build_bundle, verify_bundle, omitted_review_source


class ReviewToolTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        torch.set_num_threads(1)
        cls.temporary = tempfile.TemporaryDirectory()
        cls.root = Path(cls.temporary.name)
        cls.run_root = cls.root / "run"
        config = json.loads((Path(__file__).resolve().parents[1]/"configs/arxiv_smoke.json").read_text())
        # A numerical test fixture, not a benchmark result.
        config["training"].update(epochs=1, patience=1)
        config["controller"].update(epochs=1, patience=1)
        config["selection"]["bootstrap_reps"] = 20
        config["admission"]["bootstrap_reps"] = 20
        with contextlib.redirect_stdout(io.StringIO()):
            Pipeline(config, cls.root/"data", cls.run_root, "cpu").run()
        cls.config = config

    @classmethod
    def tearDownClass(cls):
        cls.temporary.cleanup()

    def test_numeric_replay_never_loads_pickled_models(self):
        with patch("torch.load", side_effect=AssertionError("numeric replay must not unpickle")):
            result = replay_results(self.run_root)
        self.assertEqual(result["status"], "PASS")
        self.assertTrue(result["selection_replayed"])
        self.assertFalse(result["scientific_run"])
        self.assertEqual(result["dataset"], "synthetic")

    def test_checkpoint_evaluation_reproduces_saved_outputs(self):
        evaluator = FrozenRunEvaluator(self.run_root, "cpu")
        for name in ("q0", "qN", "qC", "qD"):
            self.assertTrue(evaluator.compare(name)["agrees"])
        self.assertEqual(evaluator.data.y.accesses, [])

    def test_record_corruption_fails_without_rewriting(self):
        path = self.run_root/"final/results_summary.json"
        original = path.read_bytes()
        try:
            path.write_bytes(original + b" ")
            with self.assertRaisesRegex(EvidenceError, "hash/size mismatch"):
                replay_results(self.run_root)
            self.assertEqual(path.read_bytes(), original + b" ")
        finally:
            path.write_bytes(original)

    def test_numeric_mismatch_is_not_hidden_by_report_formatting(self):
        with self.assertRaisesRegex(EvidenceError, "recomputed"):
            assert_matches({"mean": -.01}, {"mean": -.02})
        with self.assertRaises(EvidenceError):
            assert_matches({"passed": True}, {"passed": 1})

    def test_safe_file_rejects_traversal_and_symlinks(self):
        for value in ("../outside", "/tmp/outside", "a\\b", "a/../b"):
            with self.assertRaises(EvidenceError):
                safe_file(self.run_root, value)
        link = self.run_root/"bad-link"
        link.symlink_to(self.run_root/"config.json")
        try:
            with self.assertRaises(EvidenceError):
                safe_file(self.run_root, "bad-link")
        finally:
            link.unlink()

    def test_bundle_is_portable_and_tamper_evident(self):
        target = self.root/"review.zip"
        with patch("torch.load", side_effect=AssertionError("bundle must not unpickle")):
            result = build_bundle(self.run_root, target)
        self.assertEqual(result["status"], "PASS")
        destination = self.root/"extracted"
        with zipfile.ZipFile(target) as z:
            self.assertIsNone(z.testzip())
            self.assertFalse(any("arrhenius.env" in name or "/docs/private/" in name for name in z.namelist()))
            self.assertFalse(any(Path(name).suffix in {".pt", ".pth", ".ckpt", ".safetensors", ".pkl", ".pickle"}
                                 for name in z.namelist()))
            self.assertFalse(any("/source/examples/" in name for name in z.namelist()))
            z.extractall(destination)  # This archive was just generated by this test.
        bundle = destination/"cross_morse_review"
        manifest = verify_bundle(bundle)
        self.assertFalse(manifest["checkpoints_included"])
        self.assertFalse(manifest["source_snapshot_scope"]["full_research_package_included"])
        self.assertFalse(manifest["source_snapshot_scope"]["computational_source_rewritten"])
        self.assertEqual((bundle / "source/cross_morse/core.py").read_bytes(),
                         (Path(__file__).resolve().parents[1] / "cross_morse/core.py").read_bytes())
        self.assertEqual(json.loads((bundle / "source/release/release_scope.json").read_text())["release_type"],
                         "analysis-source-subset")
        self.assertEqual(replay_results(bundle/"run")["status"], "PASS")
        f = bundle/"run/final/results_summary.json"
        f.write_text(f.read_text() + " ")
        with self.assertRaisesRegex(EvidenceError, "hash mismatch"):
            verify_bundle(bundle)
        with self.assertRaises(EvidenceError):
            build_bundle(self.run_root, target)
        with self.assertRaises(EvidenceError):
            build_bundle(self.run_root, self.run_root/"bad.zip")

    def test_review_source_subset_omits_examples_and_binary_fixtures(self):
        for relative in ("examples/runs/arxiv/train/seed_0.pt", "examples/inventory/arxiv.json",
                         "examples/generated/metrics.csv", "tests/fixtures/model.pt", "tests/fixtures/input.npz"):
            self.assertTrue(omitted_review_source(Path(relative)), relative)
        self.assertFalse(omitted_review_source(Path("cross_morse/core.py")))
        self.assertFalse(omitted_review_source(Path("scripts/reproduce_results.py")))

    def test_paired_impact_comparison_of_the_same_run_is_zero(self):
        from scripts.compare_review_runs import compare
        report = compare(self.run_root, self.run_root, reps=20)
        self.assertEqual(report["paired_after_qD_minus_before_qD"]["mean"], 0.0)
        self.assertEqual(report["changed_test_argmax_count"], 0)

    def test_result_binding_fails_on_missing_identity_or_wrong_number(self):
        from scripts.check_result_binding import check_binding
        from cross_morse.review import NumericEvidence
        e = NumericEvidence(self.run_root)
        summary = e.json("final/results_summary.json")
        declaration = {"schema_version": "result-binding-1", "status": "author_completed",
            "manuscript_identifier": "synthetic unit-test fixture, not the manuscript",
            "relationship_to_manuscript": "post_result_revision", "run_identities": e.identities,
            "results": [{"manuscript_location": "fixture", "artifact": "final/results_summary.json",
                         "json_pointer": "/paired_qD_minus_qC_ce/mean",
                         "reported_value": summary["paired_qD_minus_qC_ce"]["mean"], "absolute_tolerance": 0.0}]}
        self.assertEqual(check_binding(self.run_root, declaration)["status"], "MATCH")
        declaration["results"][0]["reported_value"] += 1
        self.assertEqual(check_binding(self.run_root, declaration)["status"], "MISMATCH")
        declaration["status"] = "template_not_evidence"
        with self.assertRaises(EvidenceError):
            check_binding(self.run_root, declaration)

    def test_parameter_inventory_counts_real_checkpoint_tensors(self):
        inventory = json.loads((self.run_root/"train/model_inventory.json").read_text())
        self.assertEqual(len(inventory["checkpoints"]), 4)
        for entry in inventory["checkpoints"]:
            self.assertEqual(entry["named_tensor_elements"], sum(t["elements"] for t in entry["tensors"]))
            self.assertGreater(entry["head_elements"], 0)


if __name__ == "__main__":
    unittest.main()
