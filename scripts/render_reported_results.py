#!/usr/bin/env python3
"""Render paper/REPORTED_RESULTS.md from paper/reported_results.json.

The JSON file is the single source of truth for every manuscript value kept in
this repository; the Markdown is generated from it so that the two cannot drift.
``--check`` exits 1 when the committed Markdown differs from a fresh rendering.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts._paper_common import DATASETS, PAPER, load_reported

TARGET = PAPER / "REPORTED_RESULTS.md"


def f(value, digits=None):
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(f(v, digits) for v in value) + "]"
    if isinstance(value, float):
        return f"{value:.{digits}f}" if digits is not None else f"{value:g}"
    return str(value)


def table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out + [""]


def render(reported: dict) -> str:
    p = reported["_provenance"]
    lines = ["# Results reported in the manuscript", "",
             "<!-- Generated by scripts/render_reported_results.py from paper/reported_results.json. Do not edit by hand. -->", "",
             f"**{p['title']}** — {', '.join(p['authors'])} ({p['affiliation']}). {p['venue']}.", "",
             f"These values are transcribed from the submitted manuscript PDFs (transcription date {p['transcription_date']}) for comparison only. "
             "They include our reported measurements, derived quantities and analytical sensitivity calculations; "
             "[sources.json](sources.json) records their PDF identities, pages and evidence types. "
             "They are not new benchmark measurements from the bundled software-validation runs. "
             "See the [paper-results overview](../docs/PAPER_RESULTS.md) for interpretation and "
             "[results/replay guide](../docs/RESULTS.md) for comparison with a completed run. Units: " + p["units"] +
             ". Sign convention: " + p["negative_is_better"] + ".", "",
             "**Admission scope:** all reported admission decisions are descriptive. The three multi-graph benchmarks "
             "reused validation for confirmation and admission; their numerical bounds do not instantiate Theorem 2. "
             "The single-graph benchmarks use dependent cores or official splits. Main Table 1, p11; "
             "Supplementary Note S26, p31.", ""]
    # Table 1
    t1 = reported["main_table_1_policy_and_deployment_ledger"]
    lines += ["## Main Table 1 — policy and deployment ledger", ""]
    rows = []
    for d in DATASETS:
        r = t1[d]
        gain = f"{r['official_gain_pp']:+.2f} {r['official_metric']} pp {f(r['official_gain_interval_pp'])}" if r["official_gain_interval_pp"] else "exactly 0"
        loss = f"{r['loss_effect_nats']:+.5f} {r['loss_name']} {f(r['loss_effect_interval_nats'])}" if r["loss_effect_interval_nats"] else "exactly 0"
        adm = f"G_admit = {r['G_admit']}; {r['admission_criterion']}"
        if r["admission_D_bar"] is not None:
            adm += f"; D̄ = {r['admission_D_bar']}"
        if r["admission_U_desc"] is not None:
            adm += f"; U_desc = {r['admission_U_desc']}"
        if r["admission_U_a"] is not None:
            adm += f"; U_a = {r['admission_U_a']}"
        rows.append([d, f"{r['qC_identity']}, E = {r['qC_E']}", r["provisional"], r["confirmation"], adm, f(r["input_fallback_fraction"]), f"{r['deployed_rule']}, E = {r['deployed_E']}", gain, loss, r["scope"]])
    lines += table(["Dataset", "qC as reported", "Provisional q̂s", "Confirmation output", "Global admission", "Input fallback", "Deployed rule", "Official gain over qC", "Paired loss effect over qC", "Scope"], rows)
    lines += ["Peptides-func: the manuscript prints the official gain in native AP units, +0.0058 AP [0.0009, 0.0107]; the table above uses AP percentage points.", ""]
    # Table 2
    t2 = reported["main_table_2_gain_and_cost_ledger"]
    lines += ["## Main Table 2 — gain and cost ledger (costs in units of one nominal full-depth execution)", ""]
    rows = []
    for d in DATASETS:
        r = t2[d]
        rows.append([d, f(r["C_qC"], 1), f"{f(r['C_expected'], 2)} (+{f(r['expected_overhead_pct'])}%)" if r["expected_overhead_pct"] is not None else f(r["C_expected"], 1),
                     f"{f(r['C_099'], 1)} {f(r['C_099_range'], 1)} (+{f(r['C_099_overhead_pct'])}%)" if r["C_099"] is not None else "—",
                     f"{f(r['C_assure'], 1)} (+{f(r['assure_overhead_pct'])}%)",
                     f"{f(r['lambda_star_mnats'], 2)} {f(r['lambda_star_range'], 1)} ({f(r['lambda_star_metric_rate'], 2)})" if r["lambda_star_mnats"] is not None else "—",
                     f(r["M_star_t_nom_thousand_input_seconds"]),
                     f"{t1[d]['loss_effect_nats']:+.5f} {t1[d]['loss_name']}" if t1[d]["loss_effect_interval_nats"] else "exactly 0"])
    lines += table(["Dataset", "C_qC", "C_expected (overhead)", "Modelled C_0.99 [tail scenarios] (overhead)", "C_assure (overhead)", "λ* millinats [range] (metric points per unit)", "M* t_nom (10³ input·s)", "Test-stage effect"], rows)
    lines += ["Expected cost uses the reported branch ledger; assurance is a separate two-branch configuration. "
              "C_0.99 is a modelled tail quantile, not the observed maximum or a hard cap. λ* and M* are derived quantities. "
              "Main Table 2, p14.", ""]
    # S4
    s4 = reported["supplementary_table_S4_target_qualification"]
    lines += ["## Supplementary Table S4 — target-regime qualification (entry contract, main Eq. 5)", ""]
    lines += table(["Dataset", "Δ̂_plant", "U(Δ_plant)", "PDD (pp)", "DIL gap (nats)", "φ_registry", "Selected strata", "U(Δ_oracle)", "Decision"],
                   [[d, f(s4[d]["Delta_plant_hat"], 4), f(s4[d]["U_Delta_plant"], 4), f(s4[d]["PDD_pp"], 2), f(s4[d]["DIL_gap_nats"], 3), f(s4[d]["phi_registry"], 2), f(s4[d]["selected_strata"], 2), f(s4[d]["U_Delta_oracle"], 4), s4[d]["decision"]] for d in DATASETS])
    lines += ["On PascalVOC-SP, COCO-SP and Peptides-func these are post-decision validation diagnostics. "
              "Training-only qualification values are not tabulated. Main p11.", ""]
    s7 = reported["supplementary_table_S7_support_audit"]
    lines += ["## Supplementary Table S7 — retained support summaries", "",
              "The withdrawn dataset-level ESS/max-weight pairs are not support measurements. Corrected common per-cell "
              "summaries are **not tabulated**; these reported fractions do not independently verify the E19 support audit.", ""]
    lines += table(["Dataset", "Trajectories", "Minimum count", "Minimum propensity", "Qualified fraction", "Corrected ESS / max weight"],
                   [[d, s7[d]["trajectories"], s7[d]["minimum_count"], f(s7[d]["minimum_propensity"], 3),
                     f(s7[d]["qualified_fraction"], 2), "not tabulated"] for d in DATASETS])
    # S12c + S20
    s12c = reported["supplementary_table_S12c_selection_rule_audit"]
    s20 = reported["supplementary_table_S20_selection_theorem_instantiation"]
    lines += ["## Supplementary Tables S12c and S20 — selection rule audit and selection-theorem instantiation", ""]
    lines += table(["Dataset", "U_min", "Registered reading (ε_eq = 0.002 on U_s)", "Selected", "Consistency", "|Q|", "|Q_s|", "r_max", "ε_eq + 2 r_max", "Slack, 12 finalists"],
                   [[d, f(s12c[d]["U_min"]), s12c[d]["registered_reading_eps_eq_0.002_on_U_s"], s12c[d]["selected"], s12c[d]["registered_reading_consistency"], s20[d]["Q_size"], s20[d]["Q_s_size"], f(s20[d]["r_max"], 4), f(s20[d]["eps_eq_plus_2r_max"], 4), f(s20[d]["slack_with_12_finalists"], 4)] for d in DATASETS])
    # S12
    s12 = reported["supplementary_table_S12_selection_ledger"]
    lines += ["## Supplementary Table S12 — route-level selection ledger (outer-fold representatives; Δ̂_s, L_s, U_s relative to the nested qC)", ""]
    rows = []
    for d in DATASETS:
        for r in s12[d]:
            rows.append([d, r["route"], r["E"], r["profile"], f(r["Delta_s_hat"], 5), f(r["L_s"], 5), f(r["U_s"], 5), r["rank"], "yes" if r["selected"] else "no", r["confirmation_output"] or "—"])
    lines += table(["Dataset", "Route", "E", "Profile", "Δ̂_s", "L_s", "U_s", "Rank", "Selected", "Confirmation output"], rows)
    lines += ["### Supplementary Table S12b — nested re-evaluation of open-loop families", "",
              "The nested estimator removes the representative-row re-selection optimism; the qC family is zero by definition. "
              "These estimates are not substituted for the full missing candidate-level trace. Supplementary p9.", ""]
    lines += table(["Dataset", "Route family", "Nested Δ̂_s, nats"],
                   [[d, r["route"], f(r["nested_Delta_s_nats"], 5)]
                    for d, rows in reported["supplementary_table_S12b_nested_open_loop_comparison"].items() for r in rows])
    # S13
    s13 = reported["supplementary_table_S13_independent_graph_admission"]
    lines += ["## Supplementary Table S13 — descriptive admission arithmetic (main Eq. 27)", "",
              "Primary moments condition on a fixed ensemble. Validation reuse makes Ua descriptive. The B=0.05/0.20 rows "
              "hold the primary mean and variance fixed: an algebraic sensitivity calculation, not a measured re-clipping run. "
              "Supplementary pp9–10.", ""]
    rows = []
    for d, r in s13.items():
        rows.append([d, r["J"], r["B"], r["delta_a"], r["epsilon_a"], f(r["D_bar"], 5), f(r["S2"], 6), f(r["penalty"], 6), f(r["U_a"], 6), r["metric_gate"], r["G_admit"]])
        for label, s in r["sensitivity"].items():
            rows.append([f"{d} ({label})", r["J"], float(label.split("=")[1]), r["delta_a"], r["epsilon_a"], f(r["D_bar"], 5), f(r["S2"], 6), f(s["penalty"], 6), f(s["U_a"], 6), r["metric_gate"], s["G_admit"]])
    lines += table(["Dataset", "J", "B", "δ_a", "ε_a", "D̄", "S²", "Penalty", "U_a", "Metric gate", "G_admit"], rows)
    # S14 / S14b
    s14 = reported["supplementary_table_S14_mechanism_contrasts_submitted_protocol"]
    lines += ["## Supplementary Table S14 — held-out mechanism contrasts (one Holm family of nine; submitted protocol)", ""]
    lines += table(["Contrast", "Effect", "95% interval", "Unit / n", "Test", "Raw P", "Holm P", "Margin", "P vs margin", "Interpretation"],
                   [[r["contrast"], f"{f(r['effect'], 5)} {r['unit']}", f(r["interval"]), f"{r['n']} {r['statistical_unit']}", r["test"], f(r["raw_P"]), f(r["holm_P"]), f(r["margin"]), f(r["P_vs_margin"]), r["interpretation"]] for r in s14])
    s14b = reported["supplementary_table_S14b_separated_data_sensitivity"] + reported.get("supplementary_table_S14b_unchanged_contrasts", [])
    lines += ["### Supplementary Table S14b — analytical sample-size sensitivity for confirmation on D_confirm", "",
              "Effects are held fixed and standard errors rescaled; this is not an observed separated-data rerun and does not repair "
              "validation reuse. The three resized contrasts are followed by the six unchanged units with re-formed Holm adjustments.", ""]
    lines += table(["Contrast", "J_old → J_new", "Effect", "95% interval", "Raw P", "Holm P", "P vs margin", "Interpretation"],
                   [[r["contrast"], f"{r['J_old']} → {r['J_new']}", f(r["effect"], 5), f(r["interval"]), f(r["raw_P"]), f(r["holm_P"]), f(r["P_vs_margin"]), r["interpretation"]] for r in s14b])
    # S15
    s15 = reported["supplementary_table_S15_method_comparison"]
    lines += ["## Supplementary Table S15 — one-row-per-method comparison (official test scores; costs in nominal executions; GPU-hours on one GH200)", ""]
    for d in DATASETS:
        block = s15[d]
        lines += [f"### {d} — score unit: {block['score_unit']}; across-seed SD range {f(block['seed_SD_range_pp'])} pp; plant parameters {block['plant_params_M']} M; HPO ceiling {block['HPO_trials']} trials", ""]
        lines += table(["Method", "Family", "Official score", "C_ctrl", "C_expected", "C_assure", "GPU-h", "Parameters (M)"],
                       [[r["method"], r["family"], f(r["official_score"]), f(r["C_ctrl"]), f(r["C_expected"]), f(r["C_assure"]), f(r["GPU_h"]), f(r["params_M"]) if r["params_M"] is not None else f(block["plant_params_M"])] for r in block["rows"]])
    # S23 + S41
    s23 = reported["supplementary_table_S23_assurance_and_expected_compute"]
    s41 = reported["supplementary_table_S41_qualification_cost_components"]
    lines += ["## Supplementary Tables S23 and S41 — compute accounting (serial costs in nominal executions; qualification in GPU-hours)", ""]
    lines += table(["Dataset", "Route/E", "Controller cost", "Comparator cost", "Fallback probability", "Assurance cost", "Expected cost", "Wall-time overhead", "r", "GPU / CPU GiB", "Qualification increment (S41)"],
                   [[d, s23[d]["route_E"], f(s23[d]["controller_cost"], 3), f(s23[d]["comparator_cost"], 3), f(s23[d]["fallback_probability"]), f(s23[d]["assurance_serial_cost"], 3), f(s23[d]["expected_serial_cost"], 3), f"{s23[d]['wall_time_overhead_pct']}%", f(s23[d]["r"]), f"{s23[d]['GPU_GiB']} / {s23[d]['CPU_GiB']}", f(s41[d]["total_qualification_increment_GPU_h"]) if s41[d]["total_qualification_increment_GPU_h"] is not None else f"— (S15 difference {s41[d].get('qualification_increment_derived_from_table_S15_GPU_h')})"] for d in DATASETS])
    # S46
    s46 = reported["supplementary_table_S46_budget_matched_frontier"]
    lines += ["## Supplementary Table S46 — reported budget-matched arm outcomes (millinats relative to qC)", "",
              "Ranges span evaluated configurations, not paired confidence intervals. Table S46b does not tabulate arm-level paired "
              "intervals, adjusted P values, actual-work observations or budget mismatch. Supplementary p29.", ""]
    lines += table(["Dataset", "Ceiling", "Feedback effect", "E3 predictor", "E4 distilled", "E5 no-observation replanning", "E6 q_B effect; overhead", "Present overhead"],
                   [[d, f(s46[d]["ceiling"]), f(s46[d]["feedback_effect_mnats"]), f"{f(s46[d]['E3_predictor'])} {f(s46[d]['E3_range'])}", f"{f(s46[d]['E4_distilled'])} {f(s46[d]['E4_range'])}", f"{f(s46[d]['E5_no_observation_replanning'])} {f(s46[d]['E5_range'])}", f"{f(s46[d]['E6_qB_effect'])}; {s46[d]['E6_overhead_pct']}% {f(s46[d]['E6_overhead_range'])}", f"{s46[d]['present_overhead_pct']}%"] for d in s46])
    # S42
    s42 = reported["supplementary_table_S42_power_of_budget_matched_test"]
    lines += ["## Supplementary Table S42 — analytical power of the budget-matched test E3", "",
              "Power uses standard errors from other reported contrasts and explicit pairing assumptions; these are sensitivity "
              "calculations, not observed E3 rejection frequencies.", ""]
    lines += table(["Dataset", "Unit", "Paired SE (nats)", "MDE (mnats) 0.05 / Holm", "Reported margin [range]", "Power at unit [range]", "Power, Holm step", "Power, seed-paired", "Power, ensemble spend"],
                   [[d, s42[d]["unit"], f(s42[d]["paired_SE_nats"]), f"{s42[d]['MDE_mnats_0.05']} / {s42[d]['MDE_mnats_holm']}", f"{s42[d]['reported_margin_mnats']} {f(s42[d]['margin_range'])}", f"{s42[d]['power_at_unit_pct']}% {f(s42[d]['power_range'])}", f"{s42[d]['power_holm_step_pct']}%", f"{f(s42[d]['power_seed_paired_pct'])}%", f"{s42[d]['power_ensemble_spend_pct']}%"] for d in s42])
    lines += ["## Other transcribed tables", "",
              "`paper/reported_results.json` also carries Supplementary Tables S6c (sensing-cost identity), S15b (per-rerun resource ledger), S16/S16b (factorials), "
              "S21 (action-gap audit), S22 (trajectory-tube audit), S23b (nominal execution time and amortization), S26b (ensemble law and break-even), S30 (oracle dispersion), "
              "S34 (budget-aware rule), S37 (input-fallback counts), S44 (per-input cost model), S45 (inserted-site attribution) and S47 (decision boundary and power), "
              "and the abstract's quantitative claims. `scripts/check_paper_constants.py` verifies the arithmetic that links these tables.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify that the committed Markdown matches a fresh rendering")
    parser.add_argument("--output", type=Path, default=TARGET)
    args = parser.parse_args(argv)
    text = render(load_reported())
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.is_file() else ""
        if current != text:
            print(f"STALE: {args.output} differs from a fresh rendering of paper/reported_results.json", file=sys.stderr)
            return 1
        print(f"{args.output} is up to date")
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
